"""The signed index: publisher side of the contract in `IMPLEMENTATION.md`.

Every key here is generated by the test and thrown away. The two real public keys in `keys.json`
are only checked structurally; their private halves are not available to anyone running tests.
"""
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import unittest
import unittest.mock
from pathlib import Path

from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
from cryptography.hazmat.primitives.asymmetric.rsa import generate_private_key
from cryptography.hazmat.primitives.serialization import (BestAvailableEncryption, Encoding, NoEncryption,
                                                          PrivateFormat, PublicFormat)

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
import catalog
import check_site
import sign_index

SERIAL = 1_788_000_000


def throwaway():
    key = Ed25519PrivateKey.generate()
    pem = key.private_bytes(Encoding.PEM, PrivateFormat.PKCS8, NoEncryption())
    return key, pem, key.public_key().public_bytes(Encoding.Raw, PublicFormat.Raw)


def keys_document(primary: bytes, standby: bytes) -> bytes:
    return catalog.canonical({"format": 1, "keys": [
        {"role": "primary", "id": sign_index.key_id(primary), "hex": primary.hex()},
        {"role": "standby", "id": sign_index.key_id(standby), "hex": standby.hex()}]})


def stock_openssl():
    """An OpenSSL 3 for the documented stock check; macOS ships LibreSSL, which cannot do it."""
    candidates = [os.environ.get("OPENSSL"), shutil.which("openssl"), "/opt/homebrew/opt/openssl@3/bin/openssl"]
    for candidate in filter(None, candidates):
        try:
            out = subprocess.run([candidate, "version"], capture_output=True, text=True, timeout=20).stdout
        except OSError:
            continue
        if out.startswith("OpenSSL 3"):
            return candidate
    return None


class Site(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name)
        self.site = self.root / "site"
        self.site.mkdir()
        self.key, self.pem, self.public = throwaway()
        _, _, self.other = throwaway()
        self.keys = self.root / "keys.json"
        self.keys.write_bytes(keys_document(self.public, self.other))
        self.index = catalog.canonical({"format": 1, "entries": [], "revoked": [], "serial": SERIAL})
        (self.site / "index.json").write_bytes(self.index)

    def sign(self):
        return sign_index.sign_site(self.site, self.keys, self.pem).read_bytes()


class SignedIndex(Site):
    def test_the_two_parts_are_a_three_key_header_and_the_exact_index_bytes(self):
        signed = self.sign()
        line, newline, rest = signed.partition(b"\n")
        self.assertEqual(newline, b"\n")
        self.assertEqual(rest, self.index)
        self.assertEqual(rest, (self.site / "index.json").read_bytes())
        header = json.loads(line)
        self.assertEqual(list(header), ["format", "key", "sig"])
        self.assertEqual(header["format"], 1)
        self.assertEqual(header["key"], hashlib.sha256(self.public).hexdigest()[:16])
        self.assertRegex(header["sig"], r"\A[0-9a-f]{128}\Z")
        self.assertEqual(line, json.dumps(header, separators=(",", ":")).encode(), "the header is compact")
        self.assertLessEqual(len(line), 256)
        self.key.public_key().verify(bytes.fromhex(header["sig"]), rest)

    def test_the_signature_is_pure_ed25519_over_the_index_alone(self):
        header = json.loads(self.sign().partition(b"\n")[0])
        self.assertEqual(bytes.fromhex(header["sig"]), self.key.sign(self.index))

    def test_one_flipped_index_byte_fails(self):
        signed = bytearray(self.sign())
        position = signed.index(b"\n") + 5
        signed[position] ^= 1
        with self.assertRaisesRegex(sign_index.Refused, "bad-signature"):
            sign_index.verify_signed(bytes(signed), sign_index.load_keys(self.keys))

    def test_one_flipped_signature_byte_fails(self):
        signed = self.sign()
        line, _, rest = signed.partition(b"\n")
        header = json.loads(line)
        header["sig"] = ("0" if header["sig"][0] != "0" else "1") + header["sig"][1:]
        tampered = json.dumps(header, separators=(",", ":")).encode() + b"\n" + rest
        with self.assertRaisesRegex(sign_index.Refused, "bad-signature"):
            sign_index.verify_signed(tampered, sign_index.load_keys(self.keys))

    def test_the_standby_key_verifies_what_the_standby_signed(self):
        standby, pem, raw = throwaway()
        self.keys.write_bytes(keys_document(self.public, raw))
        sign_index.sign_site(self.site, self.keys, pem)
        signed = (self.site / "index.signed").read_bytes()
        self.assertEqual(json.loads(signed.partition(b"\n")[0])["key"], sign_index.key_id(raw))
        sign_index.verify_signed(signed, sign_index.load_keys(self.keys))

    def test_a_key_absent_from_keys_json_is_refused_and_nothing_is_written(self):
        _, stranger, _ = throwaway()
        with self.assertRaisesRegex(sign_index.Refused, "unknown-key"):
            sign_index.sign_site(self.site, self.keys, stranger)
        self.assertFalse((self.site / "index.signed").exists())
        self.assertEqual(sorted(path.name for path in self.site.iterdir()), ["index.json"])

    def test_a_header_naming_an_unaccepted_key_is_refused(self):
        signed = self.sign()
        _, _, raw = throwaway()
        self.keys.write_bytes(keys_document(raw, self.other))
        with self.assertRaisesRegex(sign_index.Refused, "unknown-key"):
            sign_index.verify_signed(signed, sign_index.load_keys(self.keys))

    def test_keys_that_are_not_unencrypted_ed25519_pem_are_refused(self):
        rsa = generate_private_key(65537, 2048).private_bytes(Encoding.PEM, PrivateFormat.PKCS8, NoEncryption())
        locked = self.key.private_bytes(Encoding.PEM, PrivateFormat.PKCS8, BestAvailableEncryption(b"pw"))
        for pem in (rsa, locked, b"not a key", self.pem.replace(b"PRIVATE", b"PUBLIC")):
            with self.subTest(pem=pem[:30]), self.assertRaises(sign_index.Refused) as caught:
                sign_index.sign_site(self.site, self.keys, pem)
            self.assertNotIn(self.pem.split(b"\n")[1], str(caught.exception).encode(), "no key material in the message")
        self.assertFalse((self.site / "index.signed").exists())

    def test_an_index_without_a_serial_is_not_signed(self):
        for value in ({"format": 1, "entries": [], "revoked": []},
                      {"format": 1, "entries": [], "revoked": [], "serial": -1},
                      {"format": 1, "entries": [], "revoked": [], "serial": 1.5},
                      {"format": 1, "entries": [], "revoked": [], "serial": True},
                      {"format": 1, "entries": [], "revoked": [], "serial": "1760000000"}):
            with self.subTest(value=value):
                (self.site / "index.json").write_bytes(catalog.canonical(value))
                with self.assertRaisesRegex(sign_index.Refused, "no-serial"):
                    sign_index.sign_site(self.site, self.keys, self.pem)
        (self.site / "index.json").write_bytes(b"[1")
        with self.assertRaisesRegex(sign_index.Refused, "index"):
            sign_index.sign_site(self.site, self.keys, self.pem)
        self.assertFalse((self.site / "index.signed").exists())

    def test_malformed_headers_are_refused(self):
        signed = self.sign()
        line, _, rest = signed.partition(b"\n")
        header = json.loads(line)
        compact = lambda value: json.dumps(value, separators=(",", ":")).encode()
        bad = {
            "extra key": compact({**header, "extra": 1}),
            "missing sig": compact({"format": 1, "key": header["key"]}),
            "format 2": compact({**header, "format": 2}),
            "format true": compact({**header, "format": True}),
            "upper-case key": compact({**header, "key": header["key"].upper()}),
            "short key": compact({**header, "key": header["key"][:15]}),
            "short sig": compact({**header, "sig": header["sig"][:126]}),
            "sig not hex": compact({**header, "sig": "g" * 128}),
            "duplicate key": line[:-1] + b',"sig":"' + header["sig"].encode() + b'"}',
            "spaced": json.dumps(header).encode(),
            "reordered": compact({"sig": header["sig"], "key": header["key"], "format": 1}),
            "not json": b"nope",
            "too long": compact({**header, "pad": "x" * 300}),
        }
        for name, replacement in bad.items():
            with self.subTest(name), self.assertRaisesRegex(sign_index.Refused, "malformed"):
                sign_index.verify_signed(replacement + b"\n" + rest, sign_index.load_keys(self.keys))
        with self.assertRaisesRegex(sign_index.Refused, "malformed"):
            sign_index.verify_signed(line, sign_index.load_keys(self.keys))

    def test_an_index_that_changes_while_it_is_signed_leaves_no_signature(self):
        real = sign_index.verify_signed

        def tamper(signed, keys):
            (self.site / "index.json").write_bytes(self.index + b" ")
            return real(signed, keys)

        with unittest.mock.patch.object(sign_index, "verify_signed", tamper):
            with self.assertRaisesRegex(sign_index.Refused, "changed"):
                sign_index.sign_site(self.site, self.keys, self.pem)
        self.assertFalse((self.site / "index.signed").exists())

    def test_a_symlinked_index_is_refused(self):
        (self.site / "index.json").unlink()
        (self.root / "elsewhere.json").write_bytes(self.index)
        (self.site / "index.json").symlink_to(self.root / "elsewhere.json")
        with self.assertRaisesRegex(sign_index.Refused, "symlink"):
            sign_index.sign_site(self.site, self.keys, self.pem)


class Command(Site):
    def run_cli(self, **env):
        clean = {name: value for name, value in os.environ.items() if name != sign_index.SECRET}
        return subprocess.run([sys.executable, str(ROOT / "scripts" / "sign_index.py"), str(self.site), "--keys", str(self.keys)],
                              capture_output=True, text=True, env={**clean, **env}, cwd=self.root)

    def test_a_missing_or_empty_secret_fails_and_leaves_no_signature(self):
        for env in ({}, {sign_index.SECRET: ""}, {sign_index.SECRET: " \n"}):
            with self.subTest(env=env):
                done = self.run_cli(**env)
                self.assertNotEqual(done.returncode, 0)
                self.assertIn(sign_index.SECRET, done.stderr)
                self.assertFalse((self.site / "index.signed").exists())

    def test_the_secret_from_the_environment_signs_and_is_never_echoed_or_written(self):
        done = self.run_cli(**{sign_index.SECRET: self.pem.decode()})
        self.assertEqual(done.returncode, 0, done.stderr)
        body = self.pem.decode().split("\n")[1]
        self.assertNotIn(body, done.stdout + done.stderr)
        sign_index.verify_signed((self.site / "index.signed").read_bytes(), sign_index.load_keys(self.keys))
        self.assertEqual(sorted(path.name for path in self.site.iterdir()), ["index.json", "index.signed"])
        self.assertEqual(sorted(path.name for path in self.root.iterdir()), ["keys.json", "site"])
        for path in self.root.rglob("*"):
            if path.is_file():
                self.assertNotIn(body.encode(), path.read_bytes(), path.name)

    def test_a_secret_for_an_unaccepted_key_fails_the_command(self):
        _, stranger, _ = throwaway()
        done = self.run_cli(**{sign_index.SECRET: stranger.decode()})
        self.assertNotEqual(done.returncode, 0)
        self.assertIn("unknown-key", done.stderr)
        self.assertFalse((self.site / "index.signed").exists())

    @unittest.skipUnless(stock_openssl() and shutil.which("xxd"), "needs OpenSSL 3 and xxd (set OPENSSL=... on macOS)")
    def test_the_documented_stock_openssl_check_verifies_it(self):
        sign_index.sign_site(self.site, self.keys, self.pem)
        recipe = (ROOT / "IMPLEMENTATION.md").read_text()
        block = re.search(r"<!-- verify:begin -->\s*```sh\n(.*?)```\s*<!-- verify:end -->", recipe, re.S)
        self.assertIsNotNone(block, "IMPLEMENTATION.md carries the verification recipe between verify markers")
        script = block.group(1)
        work = self.root / "verify"
        work.mkdir()
        shutil.copy(self.site / "index.signed", work / "index.signed")
        path = os.path.dirname(stock_openssl()) + os.pathsep + os.environ["PATH"]
        env = {**os.environ, "PATH": path, "PUBLIC_KEY_HEX": self.public.hex()}
        done = subprocess.run(["sh", "-ec", script], cwd=work, capture_output=True, text=True, env=env)
        self.assertEqual(done.returncode, 0, done.stderr)
        self.assertIn("Signature Verified Successfully", done.stdout)
        flipped = bytearray((work / "index.signed").read_bytes())
        flipped[-3] ^= 1
        (work / "index.signed").write_bytes(bytes(flipped))
        done = subprocess.run(["sh", "-ec", script], cwd=work, capture_output=True, text=True, env=env)
        self.assertNotEqual(done.returncode, 0)


class Keys(unittest.TestCase):
    def test_every_id_is_the_first_16_hex_of_sha256_over_its_key(self):
        keys = sign_index.load_keys(ROOT / "keys.json")
        self.assertEqual([entry["role"] for entry in keys], ["primary", "standby"])
        for entry in keys:
            raw = bytes.fromhex(entry["hex"])
            self.assertEqual(len(raw), 32)
            self.assertEqual(entry["id"], hashlib.sha256(raw).hexdigest()[:16])

    def test_the_accepted_keys_are_the_contract_keys(self):
        # Changing these is a rotation: the app compiles the same two keys, so edit both together.
        self.assertEqual({entry["role"]: (entry["id"], entry["hex"]) for entry in sign_index.load_keys(ROOT / "keys.json")}, {
            "primary": ("4fe9b53b661ff2e8", "45ef4dd7f0ba0b0531014245a4b9ecbc1b1c1ebc848fa2b5d7ae5bc537c6658a"),
            "standby": ("437641d803b6932b", "c80a7613abd76a596c4c21875c4abb280c1b0e279a79b2c43e86ce9e0b41a792")})

    def test_a_keys_file_with_a_wrong_id_or_shape_is_refused(self):
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "keys.json"
            primary, standby = bytes(range(32)), bytes(range(1, 33))
            good = json.loads(keys_document(primary, standby))

            def attempt(value):
                path.write_bytes(catalog.canonical(value))
                with self.assertRaises(sign_index.Refused):
                    sign_index.load_keys(path)

            wrong = json.loads(json.dumps(good))
            wrong["keys"][0]["id"] = "0" * 16
            attempt(wrong)
            upper = json.loads(json.dumps(good))
            upper["keys"][1]["hex"] = upper["keys"][1]["hex"].upper()
            attempt(upper)
            attempt({**good, "keys": good["keys"][:1]})
            attempt({**good, "keys": [good["keys"][0], {**good["keys"][1], "role": "primary"}]})
            attempt({**good, "keys": [good["keys"][0], good["keys"][0]]})
            attempt({**good, "format": 2})
            attempt({**good, "extra": 1})
            attempt({**good, "keys": [{**good["keys"][0], "extra": 1}, good["keys"][1]]})
            attempt([])


class SiteCheck(Site):
    def test_a_site_without_a_signature_passes_unless_one_is_required(self):
        self.assertEqual(check_site.check_signature(self.site, self.keys, required=False), None)
        with self.assertRaises(AssertionError):
            check_site.check_signature(self.site, self.keys, required=True)

    def test_a_signed_site_verifies_and_a_swapped_index_does_not(self):
        self.sign()
        self.assertEqual(check_site.check_signature(self.site, self.keys, required=True), SERIAL)
        (self.site / "index.json").write_bytes(catalog.canonical({"format": 1, "entries": [], "revoked": [], "serial": SERIAL + 1}))
        with self.assertRaises(AssertionError):
            check_site.check_signature(self.site, self.keys, required=False)


class PublishSerial(unittest.TestCase):
    """The publish run fixes one serial; `HUD_INDEX_SERIAL` is the single place the workflow sets it."""

    def parse(self, argv, **env):
        import publish
        clean = {name: value for name, value in os.environ.items() if name != "HUD_INDEX_SERIAL"}
        with unittest.mock.patch.dict(os.environ, {**clean, **env}, clear=True):
            return publish.arguments(["--base-url", "https://example.invalid", *argv])

    def test_the_environment_variable_or_the_argument_sets_it(self):
        self.assertEqual(self.parse([], HUD_INDEX_SERIAL="1788000000").serial, 1788000000)
        self.assertEqual(self.parse(["--serial", "1788000001"]).serial, 1788000001)
        self.assertEqual(self.parse(["--serial", "7"], HUD_INDEX_SERIAL="1788000000").serial, 7)

    def test_a_publish_without_a_valid_serial_does_not_run(self):
        for argv, env in (([], {}), ([], {"HUD_INDEX_SERIAL": ""}), ([], {"HUD_INDEX_SERIAL": "soon"}),
                          (["--serial", "-3"], {}), (["--serial", "1.5"], {}), (["--serial", "0x10"], {})):
            with self.subTest(argv=argv, env=env), self.assertRaises(SystemExit):
                with unittest.mock.patch("sys.stderr"):
                    self.parse(argv, **env)


class Workflow(unittest.TestCase):
    """The secret is reachable from exactly one step, and only on the path that deploys."""

    @classmethod
    def setUpClass(cls):
        cls.text = (ROOT / ".github/workflows/registry.yml").read_text()
        steps, inside = [], False
        for line in cls.text.splitlines():
            if line.startswith("      - "):
                steps.append([line])
                inside = True
            elif inside and (not line.strip() or line.startswith("        ")):
                steps[-1].append(line)
            else:
                inside = False
        cls.steps = ["\n".join(step) for step in steps]

    def deploy_condition(self):
        pages = [step for step in self.steps if "upload-pages-artifact" in step]
        self.assertEqual(len(pages), 1)
        return re.search(r"^ +if: (.+)$", pages[0], re.M).group(1)

    def test_the_secret_appears_in_one_step_and_nowhere_else(self):
        self.assertEqual(self.text.count("secrets.HUD_INDEX_ED25519_KEY"), 1)
        holders = [step for step in self.steps if "secrets.HUD_INDEX_ED25519_KEY" in step]
        self.assertEqual(len(holders), 1)
        self.assertIn("scripts/sign_index.py", holders[0])
        self.assertRegex(holders[0], r"(?m)^        env:\n          HUD_INDEX_ED25519_KEY: \$\{\{ secrets\.HUD_INDEX_ED25519_KEY \}\}$")
        self.assertNotIn("echo", holders[0])
        self.assertNotIn("HUD_INDEX_ED25519_KEY", self.text.replace(holders[0], ""))

    def test_the_signing_step_runs_under_the_condition_that_gates_the_pages_upload(self):
        holder = next(step for step in self.steps if "secrets.HUD_INDEX_ED25519_KEY" in step)
        self.assertEqual(re.search(r"^ +if: (.+)$", holder, re.M).group(1), self.deploy_condition())
        self.assertIn("vars.PUBLISH_PAGES == 'true'", self.deploy_condition())
        self.assertIn("inputs.publish", self.deploy_condition())

    def test_the_signed_catalog_is_checked_before_either_upload(self):
        names = [step.splitlines()[0] for step in self.steps]
        sign = next(i for i, step in enumerate(self.steps) if "scripts/sign_index.py" in step)
        verify = next(i for i, step in enumerate(self.steps) if "--require-signed" in step)
        uploads = [i for i, step in enumerate(self.steps) if "upload-artifact" in step and "registry-catalog" in step
                   or "upload-pages-artifact" in step]
        self.assertEqual(len(uploads), 2, names)
        self.assertLess(sign, verify)
        self.assertTrue(all(verify < index for index in uploads), names)
        self.assertEqual(next(step for step in self.steps if "--require-signed" in step).count("if: " + self.deploy_condition()), 1)

    def test_one_place_sets_the_serial(self):
        self.assertEqual(self.text.count("HUD_INDEX_SERIAL="), 1)
        self.assertIn("date -u +%s", self.text)


